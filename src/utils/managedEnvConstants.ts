/**
 * Blocked keys a project may still set to the safer value: turning an OTel
 * exporter or content logging off (unless a source above project settings
 * already sets the key), or tightening Claude in Chrome.
 */
export function isProjectScopeAllowedEnvValue(
  key: string,
  value: string,
  isSetAboveProjectSettings: (key: string) => boolean,
): boolean {
  const upper = key.toUpperCase()
  if (upper === 'CLAUDE_CHROME_PERMISSION_MODE') return value === 'ask'
  if (upper === 'CLAUDE_CODE_ENABLE_CFC') return isEnvDefinedFalsy(value)
  const optsOut = PROJECT_SCOPE_OPT_OUT_CONTENT_LOGGING.has(upper)
    ? isEnvDefinedFalsy(value)
    : PROJECT_SCOPE_OPT_OUT_EXPORTERS.has(upper) && value.trim() === 'none'
  return optsOut && !isSetAboveProjectSettings(key)
}

