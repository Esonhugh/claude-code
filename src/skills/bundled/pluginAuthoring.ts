if (!declaration) throw new Error('Mods declaration generator omitted index.d.ts')

export const PLUGIN_AUTHORING_FILES: Record<string, string> = Object.freeze({
  'types/claude-code/index.d.ts': declaration.text,
  'examples/basic-mod.mjs': BASIC_MOD,
  'reference.md': REFERENCE,
})

const SKILL_PROMPT = `# Plugin Authoring

Create or debug a local Claude Code Mod using only APIs that this build actually implements.

Before editing a plugin:
1. Read \`reference.md\` from this skill's base directory.
2. Read \`types/claude-code/index.d.ts\` for exact API and event types.
3. Inspect the target plugin's \`.claude-plugin/plugin.json\`, \`hooks/hooks.json\`, module graph, custom types, and tests.
4. Prefer the smallest implementation and add or update a deterministic \`claude-code/testing\` test.
5. Run \`claude plugin validate <plugin-root>\` and \`claude plugin test <plugin-root>\` when available.

Mods are trusted plugins. This invocation did not enable a session authoring root; explain the supported plugin load/reload path instead of claiming hot reload.`

export function pluginAuthoringPrompt(args: string, authoringRoot?: string): string {
  const prompt = authoringRoot
    ? SKILL_PROMPT.replace(
        'This invocation did not enable a session authoring root; explain the supported plugin load/reload path instead of claiming hot reload.',
        `Session authoring was enabled for this session only. Create plugins as direct child directories of \`${authoringRoot}\`; valid child plugins load after the current turn and are watched for later changes.`,
      ).trim()
    : SKILL_PROMPT.trim()
  return args.trim() === ''
    ? prompt
    : `${prompt}\n\n## User Request\n\n${args}`
}

export function registerPluginAuthoringSkill(): void {
  registerBundledSkill({
    name: 'plugin-authoring',
    description: DESCRIPTION,
    userInvocable: true,
    files: PLUGIN_AUTHORING_FILES,
    async getPromptForCommand(args, context) {
      const consent = context.requestModAuthoringConsent
        ? await context.requestModAuthoringConsent(context.abortController.signal)
        : { enabled: false as const }
      return [
        {
          type: 'text',
          text: pluginAuthoringPrompt(
            args,
            consent.enabled ? consent.root : undefined,
          ),
        },
      ]
    },
  })
}
