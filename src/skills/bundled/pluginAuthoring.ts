const DESCRIPTION =
  'Make a mod: a pane, band, status line, toast, or hook inside Claude Code, written as a plugin of function hooks. Load before writing or debugging a hooks module.'

const REFERENCE = `# Local Mods authoring reference

A Mod is a trusted plugin using Function Hooks. The minimum layout is:

- \`.claude-plugin/plugin.json\`
- \`hooks/hooks.json\`
- one module named by \`hooks.json\`

## Manifest and entrypoint

\`.claude-plugin/plugin.json\` uses the normal plugin manifest fields such as \`name\`, \`version\`, and \`description\`. It may set \`types\` to an author-owned declaration file such as \`./types/index.d.ts\`.

\`hooks/hooks.json\` declares module paths relative to itself:

\`{ "modules": ["./register.mjs"] }\`

Each module exports \`register(on)\`. Register hooks synchronously. Hook handlers receive the scoped host API as \`$\`, the event input, and (for middleware hooks) \`next\`.

## Implemented local API

Use the attached \`types/claude-code/index.d.ts\` as the source of truth for this build. It is generated by the same \`generateModDeclarationFiles\` implementation that installs declarations beneath a loaded plugin's \`.claude-plugin/types\` directory; do not invent API names from memory.

The local runtime includes lifecycle and session hooks, tool/prompt/turn middleware, commands and agents, scoped config/fs/http/process/store capabilities, versioned state helpers, and terminal/remote UI rendering. UI components and event inputs are described by the generated declarations.

Plugin state keys are scoped by plugin and key. Prefer \`$.state.get\`, \`$.state.set\`, and the declared state helpers rather than module globals when data should survive activation replacement.

Plugin discovery reads the manifest and \`hooks/hooks.json\`, resolves declared modules, scans their static relative imports, and validates paths before activation. Keep the module graph inside the plugin, use static relative imports, and avoid depending on arbitrary Node globals, npm/native modules, or dynamic imports.

## Validate and test

Run \`claude plugin validate /absolute/path/to/plugin\` for manifest, hook-module, dependency, state-contract, and content validation.

Put tests under \`tests/\`, import from \`claude-code/testing\`, and run \`claude plugin test /absolute/path/to/plugin\`. Tests may register host stubs with \`on(...)\`, drive the scoped \`$\` API, mount UI with \`$.ui.mount(...)\`, query rendered elements, send input, and unmount. Keep tests deterministic and credential-free.

## Current boundary

Treat Mods as trusted code: the worker/VM is not an OS security sandbox.

Only after the interactive host confirms consent may you use the session authoring root returned in this invocation. Create plugins as direct child directories of that root; changes during a turn are loaded after the current turn and watched for later changes. Enabling authoring does not prove that a plugin loaded successfully: check validation and runtime diagnostics.

Choosing \`Not now\` does not enable session authoring. Without confirmed consent or an interactive host, use supported plugin loading and \`/reload-plugins\` instead. Consent belongs to the current session; clear or fork does not inherit it. Resuming the same session can restore its recorded authoring root.
`

