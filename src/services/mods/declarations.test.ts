function diagnostics(files: Readonly<Record<string, string>>, roots: readonly string[]): readonly ts.Diagnostic[] {
  const options: ts.CompilerOptions = {
    strict: true,
    noEmit: true,
    skipLibCheck: true,
    target: ts.ScriptTarget.ES2023,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    lib: ['lib.es2023.d.ts'],
    types: [],
    jsx: ts.JsxEmit.React,
    jsxFactory: 'h',
    jsxFragmentFactory: 'Fragment',
  }
  const host = ts.createCompilerHost(options)
  const read = host.readFile.bind(host)
  const exists = host.fileExists.bind(host)
  const directoryExists = host.directoryExists?.bind(host)
  host.directoryExists = directory => Object.keys(files).some(file => file.startsWith(`${directory}/`)) || directoryExists?.(directory) === true
  host.readFile = file => files[file] ?? read(file)
  host.fileExists = file => Object.hasOwn(files, file) || exists(file)
  return ts.getPreEmitDiagnostics(ts.createProgram([...roots], options, host))
}

function messages(items: readonly ts.Diagnostic[]): string {
  return items.map(item => ts.flattenDiagnosticMessageText(item.messageText, '\n')).join('\n')
}

